var (
	lookupOnce sync.Once
	lookupMap  map[string]struct{}
)

// initLookup 初始化哈希查找表（懒初始化）
func initLookup() {
	lookupOnce.Do(func() {
		lookupMap = make(map[string]struct{}, len(idioms))
		for _, v := range idioms {
			lookupMap[v] = struct{}{}
		}
	})
}

// Contains 判断给定字符串是否为收录的成语。
//
// 时间复杂度 O(1)（哈希查找）。
func Contains(idiom string) bool {
	initLookup()
	_, ok := lookupMap[idiom]
	return ok
}

// Random 随机返回一条收录的成语。
func Random() string {
	return idioms[rand.Intn(len(idioms))]
}

// All 返回所有收录成语的副本（供遍历使用）。
func All() []string {
	result := make([]string, len(idioms))
	copy(result, idioms)
	return result
}

// Count 返回词典中成语总数。
func Count() int {
	return len(idioms)
}
