// Package execution 动作调用的执行侧职责：把已经决定要执行的调用跑完，
// 并如实报告结果。
//
// 这里承载与"调用过程本身"有关、与"调用什么"无关的部分：
//
//   - 命令通道的参数安全校验与权限串解析（safety.go）
//   - 调用失败时回填给模型的提示文案（retry.go）
//
// 执行侧不关心动作如何被选择，也不关心调用为什么被允许——那分别属于选择层
// 与策略层，因此本包不引入选择、检索、审批决策等概念。
//
// # 依赖方向
//
// 本包只依赖协议层与框架层，不依赖 ai 包，也不持有 *Plugin。需要其它 owner
// 的数据时，由本包作为消费方声明最小接口（能力端口），再在装配点把具体实现
// 适配进来。端口只暴露完成该职责所必需的操作，因此"执行侧依赖了什么"可以
// 直接从接口读出。
