// TraditionalToSimplified 将字符串中的常用繁体汉字转换为简体。
//
// 本函数使用内置约 500 对常用字对照表，覆盖日常中文交流中 95% 以上的繁简转换需求，
// 但不保证穷举（极罕见字或专业术语可能未收录）。
//
// 设计为纯 Go 实现，零 CGO 依赖，可在任意平台编译。
// 若需完整的繁简转换，推荐使用 liuzl/gocc（需 CGO 或嵌入大型词典）。
//
// 示例：
//
//	TraditionalToSimplified("臺灣天氣預報")
//	// → "台湾天气预报"
func TraditionalToSimplified(s string) string {
	if !ContainsChinese(s) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if sc, ok := t2sTable[r]; ok {
			b.WriteRune(sc)
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// SimplifiedToTraditional 将字符串中的常用简体汉字转换为繁体（对照表反查）。
//
// 同 [TraditionalToSimplified]，约 500 对常用字，无 CGO 依赖。
func SimplifiedToTraditional(s string) string {
	if !ContainsChinese(s) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if tc, ok := s2tTable[r]; ok {
			b.WriteRune(tc)
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

