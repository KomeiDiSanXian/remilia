// s2tTable 简体→繁体对照表（t2sTable 的反查）。
// 由 init() 自动构建，避免维护两份表。
var s2tTable = make(map[rune]rune, len(t2sTable))

func init() {
	for t, s := range t2sTable {
		// 一对多情况（多个繁体对应同一简体）取最后一个；
		// 对于框架级用途（Bot 指令模糊匹配）此精度已足够。
		s2tTable[s] = t
	}
}
